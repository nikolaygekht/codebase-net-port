using AwesomeAssertions;
using CodeBase.Net.Cdx;
using CodeBase.Net.Expressions;
using CodeBase.Net.TestUtils;
using Xunit;

namespace CodeBase.Net.Golden;

/// <summary>
/// Visual FoxPro's collations on the code pages it has them on, against the keys Visual FoxPro wrote on each.
///
/// Each oracle table is written by Visual FoxPro 9 under one code page and one collation (ADR-44):
/// every byte alone, every byte beside its partners, runs of twelve, and for a named collation rows
/// aimed at its contractions, under one tag. GENERAL on cp437 and cp1252 is weighed with CodeBase's
/// own tables, so those two are the control: VFP's keys must rebuild through them, and do. Everywhere
/// else the port's tables were recovered from these very keys -- GENERAL's cp850 among them, because
/// CodeBase's cp850 table keys thorn as one head and a tail where VFP keys the two heads T and H -- so
/// the library's tables are held equal to a fresh recovery as well as rebuilding every key.
///
/// Governing decisions: ADR-86, ADR-87, ADR-88.
/// </summary>
[Trait("Layer", "Golden")]
public sealed class VisualFoxProGeneralGoldenTests
{
    /// <summary>Every oracle table, read off its dump's first line: the collation VFP built it with, and the code page.</summary>
    public static TheoryData<string, int> Oracles => [.. OracleList()];

    /// <summary>The tables whose weights were recovered from VFP's keys: all but GENERAL on cp437 and cp1252.</summary>
    public static TheoryData<string, int> Recovered =>
        [.. OracleList().Where(o => !(o.Collation == "GENERAL" && o.CodePage is 437 or 1252))];

    [Fact]
    public void TheGateCoversEveryCollationVisualFoxProBuilt()
    {
        // GENERAL on thirteen code pages, and the named collations on the fifty-one pairs VFP builds
        // them on (vfpcoll.prg's survey). A table that went missing would otherwise just not be tested.
        OracleList().Count(o => o.Collation == "GENERAL").Should().Be(13);
        OracleList().Count(o => o.Collation != "GENERAL").Should().Be(51);
    }

    private static List<(string Collation, int CodePage)> OracleList()
    {
        List<(string, int)> found = [];
        foreach (string dump in Directory.GetFiles(Path.GetDirectoryName(Corpus.PathOf("vfp/VFPFUNC.DBF"))!, "VFP*.vfp.dump.txt"))
        {
            string first = File.ReadLines(dump).First();
            System.Text.RegularExpressions.Match m = System.Text.RegularExpressions.Regex.Match(first, @"oracle: (\w+) on code page (\d+)$");
            if (m.Success)
                found.Add((m.Groups[1].Value, int.Parse(m.Groups[2].Value, System.Globalization.CultureInfo.InvariantCulture)));
        }

        return [.. found.OrderBy(o => o.Item1, StringComparer.Ordinal).ThenBy(o => o.Item2)];
    }

    [Theory]
    [MemberData(nameof(Oracles))]
    public void EveryKeyVisualFoxProStoredIsRebuiltFromItsRecord(string collation, int codePage)
    {
        using CodeBaseEngine engine = new();
        using Table table = engine.OpenTable(Corpus.PathOf(Oracle(collation, codePage)));

        table.CodePageNumber.Should().Be(codePage);

        CdxTag tag = table.Tags["G"].Inner;
        SeekConverter converter = SeekConverter.For(
            tag.Header, [.. table.Fields], codePage, table.ExpressionOptions, "VFP", table.LongFieldNames);
        ExpressionEvaluator evaluator = new(converter.Compiled);
        List<string> failures = [];
        int compared = 0;
        TagCursor cursor = tag.OpenCursor();

        for (bool on = cursor.Top(); on; on = cursor.Next())
        {
            IndexEntry stored = cursor.Current;
            table.Go((int)stored.Record);

            byte[] built = new byte[converter.KeyLength];
            RecordKey.WriteValue(converter, evaluator.Evaluate(table.EvaluationContext()), built);

            compared++;
            if (!built.AsSpan().SequenceEqual(stored.Key))
            {
                failures.Add(
                    $"record {stored.Record} {Convert.ToHexString(table.GetRawBytes(table.Fields["K"]))}: " +
                    $"{Convert.ToHexString(built)}, stored {Convert.ToHexString(stored.Key)}");
            }
        }

        string.Join(Environment.NewLine, failures.Take(10)).Should().BeEmpty($"{failures.Count} keys disagree, {collation} cp{codePage}");
        compared.Should().Be(table.RecordCount, "every record is in the tag once");
    }

    [Theory]
    [MemberData(nameof(Recovered))]
    public void TheLibrarysTablesAreWhatVisualFoxProsKeysSay(string collation, int codePage)
    {
        // The tables were generated by this recovery; holding them to it keeps the two from drifting.
        VisualFoxProGeneralRecovery.Weights recovered = VisualFoxProGeneralRecovery.Recover(Corpus.PathOf(Oracle(collation, codePage)));
        CollationName name = NameOf(collation);

        CollationWeights.TableFor(name, codePage).ToArray().Should().Equal(recovered.Table);
        CollationWeights.ExpansionsFor(name, codePage).ToArray().Should().Equal(recovered.Expansions);
        CollationWeights.SequencesFor(name, codePage).ToArray().Should().Equal(recovered.Sequences);
    }

    [Theory]
    [MemberData(nameof(Oracles))]
    public void TheOracleStillHoldsWhatTheRebuildRestsOn(string collation, int codePage)
    {
        // Every byte alone and the runs at least; a table that lost a block would rebuild fewer keys
        // and still pass.
        using CodeBaseEngine engine = new();
        using Table table = engine.OpenTable(Corpus.PathOf(Oracle(collation, codePage)));

        table.RecordCount.Should().BeGreaterThanOrEqualTo(256 + 19);
        table.Tags["G"].Inner.Header.Collation.Should().Be(NameOf(collation));
        table.Tags["G"].Inner.Header.CollationText.Should().Be(collation);
    }

    private static CollationName NameOf(string collation) => collation switch
    {
        "GENERAL" => CollationName.General,
        _ => Enum.Parse<CollationName>(collation, ignoreCase: true),
    };

    private static string Oracle(string collation, int codePage) =>
        $"vfp/VFP{(collation == "GENERAL" ? "G" : collation[..3])}{codePage}.DBF";
}
