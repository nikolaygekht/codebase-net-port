// bestfit — writes net/CodeBase.Net/Expressions/WindowsBestFitSupplement.cs.
//
// CodeBase narrows a wide string with WideCharToMultiByte(CP_ACP, 0, ...) (e4functi.c:2694-2716),
// so Windows' best-fit mapping decides what STR() of a 'W' field gives. The port narrows by the
// table's code page through .NET's encoding, whose best-fit agrees with Windows' except for a few
// code points per code page. This tool asks Windows for every UTF-16 code unit, one at a time, on
// each single-byte code page the library names, and writes down where .NET answers differently.
// Run it on Windows: dotnet run --project test-files-generator/bestfit -- <output .cs path>.

using System.Runtime.InteropServices;
using System.Text;

if (args.Length != 1)
{
    Console.Error.WriteLine("usage: bestfit <output .cs path>");
    return 2;
}

if (!OperatingSystem.IsWindows())
{
    Console.Error.WriteLine("bestfit asks Windows what WideCharToMultiByte does, so it runs on Windows only.");
    return 2;
}

Encoding.RegisterProvider(CodePagesEncodingProvider.Instance);

// The single-byte code pages CodePageMap names that Windows defines. 620 and 895 are FoxPro-era DOS
// code pages no one supplies; 932, 936, 949 and 950 are multi-byte, which STR() of a wide field refuses.
int[] codePages = [437, 737, 850, 852, 857, 861, 865, 866, 874, 1250, 1251, 1252, 1253, 1254, 1255, 1256, 10000, 10006, 10007, 10029];

var output = new StringBuilder();
output.Append("""
    // <auto-generated>
    // Written by test-files-generator/bestfit from Windows' WideCharToMultiByte. Do not edit by hand;
    // run the tool again instead (test-files-generator/bestfit/README.md).
    // </auto-generated>

    namespace CodeBase.Net.Expressions;

    /// <summary>
    /// The code points Windows best-fits and .NET's code-page encodings do not, per single-byte code page.
    ///
    /// CodeBase narrows a wide string with Windows' WideCharToMultiByte, whose best-fit mapping turns
    /// characters a code page lacks into a near one. .NET's encodings do the same for nearly every code
    /// point and give a question mark for the few listed here, nearly all of them spaces, dashes and
    /// quotation marks from General Punctuation. U+2000 is among them on cp1251, and it is what CodeBase
    /// fills an unassigned wide character with.
    /// A code page with nothing listed has no entry.
    /// </summary>
    internal static class WindowsBestFitSupplement
    {
        /// <summary>
        /// Gets the supplement, keyed by code page number and then by code point.
        /// </summary>
        /// <value>The byte Windows gives for each code point .NET does not map.</value>
        public static IReadOnlyDictionary<int, IReadOnlyDictionary<char, byte>> ByCodePage { get; } =
            new Dictionary<int, IReadOnlyDictionary<char, byte>>
            {

    """);

int total = 0;
byte[] windows = new byte[8];

foreach (int codePage in codePages)
{
    Encoding encoding = Encoding.GetEncoding(codePage);
    var entries = new List<(int CodePoint, byte Byte)>();

    for (int unit = 0; unit <= 0xFFFF; unit++)
    {
        string text = ((char)unit).ToString();
        byte[] dotnet = encoding.GetBytes(text);
        int written = WideCharToMultiByte((uint)codePage, 0, text, 1, windows, windows.Length, IntPtr.Zero, IntPtr.Zero);

        if (written != 1 || dotnet.Length != 1)
            throw new InvalidOperationException($"cp{codePage} U+{unit:X4}: not one byte each ({written}, {dotnet.Length}).");

        if (windows[0] != dotnet[0])
        {
            if (dotnet[0] != (byte)'?')
                throw new InvalidOperationException($"cp{codePage} U+{unit:X4}: .NET maps it to 0x{dotnet[0]:X2}, Windows to 0x{windows[0]:X2}.");

            entries.Add((unit, windows[0]));
        }
    }

    if (entries.Count == 0)
        continue;

    total += entries.Count;
    output.Append($"            [{codePage}] = new Dictionary<char, byte>\n            {{\n");
    foreach ((int codePoint, byte value) in entries)
        output.Append($"                ['\\u{codePoint:X4}'] = 0x{value:X2},\n");
    output.Append("            },\n");
}

output.Append("""
            };
    }

    """);

File.WriteAllText(args[0], output.ToString().ReplaceLineEndings("\n"), new UTF8Encoding(false));
Console.WriteLine($"{total} entries over {codePages.Length} code pages -> {args[0]}");
return 0;

[DllImport("kernel32.dll", CharSet = CharSet.Unicode, SetLastError = true)]
static extern int WideCharToMultiByte(
    uint codePage, uint flags, string text, int count, byte[] output, int outputSize, IntPtr defaultChar, IntPtr usedDefault);
