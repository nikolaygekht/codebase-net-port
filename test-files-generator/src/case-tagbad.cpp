/* ==========================================================================
 * case-tagbad.cpp — TAGBAD.DBF + TAGBAD.cdx
 *
 * The file the reference writes and then refuses to open. T_TEXT is built by
 * i4create in machine order; G_DESC, DESCEND(K_TEXT) under GENERAL, is added
 * by i4tagAdd. i4create would parse that expression again once the collation
 * is set (i4create.c:1010-1025); i4tagAdd does not (i4add.c:746-760), so it
 * writes key length 20, the unwidened length. At open the collation is read
 * from the header before the parse, the expression resolves to 40, and the
 * check of the computed length against the header refuses the index (E84901,
 * e4index, i4init.c:485-490). CDX-FORMAT.md section 8.6 has the comparison of
 * the two creation paths.
 *
 * What it is for: a reader that checks a tag's key length at open must refuse
 * this file where the reference does, and one that does not would build seek
 * keys of 40 bytes for a tag whose keys are 20. The refusal is recorded in
 * TAGBAD.open.dump.txt. No index dump can be taken — the reference cannot open
 * the index — so the table is dumped without it.
 *
 * Added 2026-10-31, step 012 sub-step 5c. The data below belongs to this case
 * alone. Other cases keep their own copies on purpose — see cases.h.
 * ========================================================================== */

#include "d4all.h"

#include <stdio.h>

#include "util.h"
#include "cases.h"

#define ROWS 4           /* records in this table */

/* --------------------------------------------------------------- test data */

static const char *TEXTS[ROWS] = { "cafe", "zebra", "alpha", "CAFE" };

/* Opens the index by name and records what the reference answered. A refusal
 * is the expected outcome; an index that opens fails the case, because then
 * the file no longer shows what it exists to show. */
static int dumpOpen( CODE4 *cb, const char *outDir )
{
   char dbfPath[520], indexPath[520], dumpPath[520];
   DATA4 *data;
   INDEX4 *index;
   FILE *out;
   int savedAutoOpen, refused;

   sprintf( dbfPath, "%s\\TAGBAD.DBF", outDir );
   sprintf( indexPath, "%s\\TAGBAD.cdx", outDir );
   sprintf( dumpPath, "%s\\TAGBAD.open.dump.txt", outDir );

   savedAutoOpen = cb->autoOpen;
   cb->autoOpen = 0;
   data = d4open( cb, dbfPath );
   cb->autoOpen = savedAutoOpen;

   if ( data == 0 )
      return fail( cb, "reopen TAGBAD.DBF" );

   index = i4open( data, indexPath );
   refused = error4code( cb );
   error4set( cb, 0 );
   d4close( data );

   if ( index != 0 || refused >= 0 )
   {
      fprintf( stderr, "  ERROR: TAGBAD.cdx opened; the case no longer shows the refusal\n" );
      return 1;
   }

   out = fopen( dumpPath, "wb" );   /* "wb": LF endings on any host */
   if ( out == 0 )
   {
      fprintf( stderr, "  ERROR: cannot create %s\n", dumpPath );
      return 1;
   }

   fprintf( out, "# CodeBase.NET corpus open dump\n" );
   fprintf( out, "# Generated by test-files-generator from the original CodeBase C library.\n" );
   fprintf( out, "# Do not edit by hand; regenerate instead.\n" );
   fprintf( out, "file         TAGBAD.cdx\n" );
   fprintf( out, "table        TAGBAD.DBF\n" );
   fprintf( out, "open         refused errorCode=%d\n", refused );
   fclose( out );

   printf( "  dump -> TAGBAD.open.dump.txt  (refused, errorCode=%d)\n", refused );
   return 0;
}

/* ------------------------------------------------------------------- case */

int caseTagBad( CODE4 *cb, const char *outDir )
{
   static FIELD4INFO fields[] =
   {
      /* name           type  len  dec  nulls  */
      { (char *)"ID",      'I',   4,   0,   0 },
      { (char *)"K_TEXT",  'C',  20,   0,   0 },
      { 0, 0, 0, 0, 0 }
   };

   /* name       expression   filter  unique  descending */
   static TAG4INFO machineTag[] =
   {
      { (char *)"T_TEXT", (char *)"K_TEXT", 0, 0, 0 },
      { 0, 0, 0, 0, 0 }
   };

   static TAG4INFO generalTag[] =
   {
      { (char *)"G_DESC", (char *)"DESCEND(K_TEXT)", 0, 0, 0 },
      { 0, 0, 0, 0, 0 }
   };

   char path[520];
   DATA4 *data;
   INDEX4 *index;
   int i, rc, savedAutoOpen;

   sprintf( path, "%s\\TAGBAD.DBF", outDir );
   printf( "TAGBAD.DBF (0x30 + CDX, a GENERAL DESCEND tag added by i4tagAdd) ... " );

   cb->compatibility = 30;

   c4setCodePage( cb, cp1252 );
   data = d4create( cb, path, fields, 0 );
   c4setCodePage( cb, cp0 );

   if ( data == 0 )
      return fail( cb, "d4create TAGBAD.DBF" );

   for ( i = 0; i < ROWS; i++ )
   {
      if ( d4appendStart( data, 0 ) < 0 )  { d4close( data ); return fail( cb, "d4appendStart" ); }
      d4blank( data );

      f4assignLong( d4fieldJ( data, 1 ), (long)i );
      f4assign    ( d4fieldJ( data, 2 ), TEXTS[i] );

      if ( d4append( data ) < 0 )          { d4close( data ); return fail( cb, "d4append" ); }
   }

   index = i4create( data, 0, machineTag );
   if ( index == 0 )
   {
      d4close( data );
      return fail( cb, "i4create TAGBAD.cdx" );
   }

   c4setCollatingSequence( cb, sort4general );
   rc = i4tagAdd( index, generalTag );
   c4setCollatingSequence( cb, sort4machine );

   if ( rc < 0 )
   {
      d4close( data );
      return fail( cb, "i4tagAdd G_DESC" );
   }

   printf( "%d records, 2 tags\n", ROWS );

   /* The table dump reopens the table, which would open its production index
    * and be refused; it is taken without the index. */
   savedAutoOpen = cb->autoOpen;
   cb->autoOpen = 0;
   rc = finish( cb, data, outDir, "TAGBAD.DBF" );
   cb->autoOpen = savedAutoOpen;

   if ( rc == 0 )
      rc = dumpOpen( cb, outDir );

   return rc;
}
