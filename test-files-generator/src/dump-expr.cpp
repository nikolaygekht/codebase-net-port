/* ==========================================================================
 * dump-expr.cpp — the expression oracle: what the C library's own parser and
 * evaluator answer, recorded so the port can be compared against it.
 *
 * WHY THE NODE ARRAY IS DUMPED, NOT ONLY THE VALUE
 * ------------------------------------------------
 * v4functions is (operation x type): a missing overload row does not fail, it
 * selects the neighbouring row and produces a plausible value (e4parse.c:207-214).
 * EXPR4 keeps the resolution it chose -- info[i].functionI is the row index --
 * so recording the array turns that silent failure into a mismatched integer.
 * It also pins the parser's output shape and the six implicit promotions, which
 * are rewrites of a producer node's row (e4parse.c:227-285).
 *
 * WHY VALUES ARE RAW BYTES
 * ------------------------
 * expr4vary hands back the result buffer. Numeric results are doubles; printing
 * them as text would make formatting a second thing to get right and would hide
 * exactly the low bits the FOX key transform depends on. Everything is escaped
 * by the shared dumpEscapedBytes, so a value and a key unescape the same way.
 *
 * WHY A FIELD EXPRESSION IS EVALUATED TWICE
 * -----------------------------------------
 * A computed node sets its isNull on a null operand (e4functi.c:334-337,
 * :2325-2327) and nothing clears it; only the field loaders reset theirs
 * (e4fieldCopy, :608-616). So one EXPR4
 * evaluated record after record carries a null forward into every record after
 * the first null one, wherever a parent reads a computed child's isNull. The
 * port does not replicate that (ADR-61), so each field expression is also parsed
 * afresh for every record, and a "fresh" line records the value wherever the
 * two readings differ. No fresh line means they agree.
 *
 * THREE MECHANICS, none of them obvious:
 *   - expr4parseLow is the const-correct entry point and takes the tag context;
 *     expr4parse( DATA4 *, char * ) is the legacy signature (e4parse.c:2698).
 *   - E4PARM_HIGH rejects a null DATA4 (e4parse.c:1065-1070), so even a
 *     constant expression needs an open table to parse against.
 *   - expr4parseLow returns immediately while error4code is negative
 *     (e4parse.c:1073), so a refused expression must have the code cleared or
 *     every later parse reports that same failure.
 * ========================================================================== */

#include "d4all.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "util.h"
#include "dump-expr.h"

/* Type codes are single characters (d4defs.h:2776-2790) but not all printable
 * -- r4numDoub is 'n', r4dateDoub is 'd', and the r5* family runs into control
 * codes. Print the character when it is readable and the number always. */
static void dumpTypeCode( FILE *fp, int code )
{
   if ( code >= 0x20 && code <= 0x7E )
      fprintf( fp, "'%c'(%d)", (char)code, code );
   else
      fprintf( fp, "---(%d)", code );
}

static void dumpHeader( FILE *fp, const char *what )
{
   fprintf( fp, "# CodeBase.NET corpus %s dump\n", what );
   fprintf( fp, "# Generated by test-files-generator from the original CodeBase C library.\n" );
   fprintf( fp, "# Do not edit by hand; regenerate instead.\n" );
}

/* -------------------------------------------------------- the function table */

int dumpFunctionTable( const char *outDir )
{
   const E4FUNCTIONS *fns = e4functions();
   char path[520];
   FILE *fp;
   int i, p;

   sprintf( path, "%s\\FUNCTIONS.dump.txt", outDir );
   fp = fopen( path, "wb" );
   if ( fp == 0 )
   {
      fprintf( stderr, "  ERROR: cannot write %s\n", path );
      return 1;
   }

   dumpHeader( fp, "function table" );
   fprintf( fp, "source       v4functions[EXPR4NUM_FUNCTIONS], e4functi.c\n" );
   fprintf( fp, "count        %d\n", EXPR4NUM_FUNCTIONS );
   fprintf( fp, "\n[functions]\n" );

   for ( i = 0; i < EXPR4NUM_FUNCTIONS; i++ )
   {
      const E4FUNCTIONS *f = fns + i;

      fprintf( fp, "%3d ", i );
      dumpEscapedBytes( fp, f->name == 0 ? "" : f->name,
                        f->name == 0 ? 0 : (unsigned long)strlen( f->name ) );
      fprintf( fp, " code=%d nameLen=%d prio=%d numParms=%d return=",
               (int)f->code, (int)f->nameLen, (int)f->priority, (int)f->numParms );
      dumpTypeCode( fp, (unsigned char)f->returnType );
      fprintf( fp, " parms=" );
      for ( p = 0; p < E4MAX_PARMS; p++ )
      {
         if ( p > 0 )
            fputc( ',', fp );
         dumpTypeCode( fp, (unsigned char)f->type[p] );
      }
      fputc( '\n', fp );
   }

   fclose( fp );
   return 0;
}

/* ------------------------------------------------------- expression records */

/* The compiled form: what overload resolution chose, node by node. resultPos
 * and i1 are deliberately absent -- they are positions in the C's evaluation
 * stack and its constant pool, artefacts of a stack machine that returns
 * pointers, and carry nothing a value-returning evaluator can reproduce. */
static void dumpNodes( FILE *fp, EXPR4 *expr )
{
   int i;

   fprintf( fp, "  compiled type=" );
   dumpTypeCode( fp, expr->type );
   fprintf( fp, " len=%d keyLen=%d hasTrim=%d nodes=%d\n",
            expr->len, expr4keyLen( expr ), (int)expr->hasTrim, expr->infoN );

   for ( i = 0; i < expr->infoN; i++ )
   {
      E4INFO *info = expr->info + i;

      fprintf( fp, "    node %2d row=%d len=%d numParms=%d numEntries=%d fieldNo=%d i2=%d\n",
               i, info->functionI, info->len, info->numParms,
               info->numEntries, (int)info->fieldNo, info->i2 );
   }
}

/* Evaluate at the current record and write the raw result bytes. */
static void dumpValue( FILE *fp, CODE4 *cb, EXPR4 *expr, const char *lead )
{
   char *result = 0;
   int len = expr4vary( expr, &result );

   if ( len < 0 || result == 0 )
   {
      fprintf( fp, "%s eval-failed rc=%d errorCode=%d\n", lead, len, (int)error4code( cb ) );
      error4set( cb, 0 );
      return;
   }

   fprintf( fp, "%s len=%d ", lead, len );
   dumpEscapedBytes( fp, result, (unsigned long)len );
   fputc( '\n', fp );
}

/* A value kept past the next evaluation: expr4vary's result lives in the
 * CODE4's shared work buffer, which any other expression overwrites. */
typedef struct
{
   int len;
   int errorCode;
   char *bytes;
} KEPTVALUE;

static void keepValue( CODE4 *cb, EXPR4 *expr, KEPTVALUE *kept )
{
   char *result = 0;

   kept->len = expr4vary( expr, &result );
   kept->errorCode = 0;
   kept->bytes = 0;
   if ( kept->len < 0 || result == 0 )
   {
      kept->errorCode = (int)error4code( cb );
      error4set( cb, 0 );
      return;
   }

   kept->bytes = (char *)malloc( kept->len > 0 ? kept->len : 1 );
   memcpy( kept->bytes, result, kept->len );
}

/* The second reading: the same text parsed anew for one record, so no isNull
 * survives from an earlier record. Written only where it differs. */
static void dumpFreshValue( FILE *fp, CODE4 *cb, DATA4 *data, const char *text,
                            long rec, const KEPTVALUE *sticky )
{
   EXPR4 *fresh;
   char *result = 0;
   int len;

   if ( error4code( cb ) != 0 )
      error4set( cb, 0 );

   fresh = expr4parseLow( data, text, 0 );
   if ( fresh == 0 )
   {
      fprintf( fp, "  fresh %ld PARSE FAILED errorCode=%d\n", rec, (int)error4code( cb ) );
      error4set( cb, 0 );
      return;
   }

   len = expr4vary( fresh, &result );
   if ( len < 0 || result == 0 )
   {
      fprintf( fp, "  fresh %ld eval-failed rc=%d errorCode=%d\n", rec, len, (int)error4code( cb ) );
      error4set( cb, 0 );
   }
   else if ( sticky->bytes == 0 || len != sticky->len || memcmp( result, sticky->bytes, len ) != 0 )
   {
      fprintf( fp, "  fresh %ld len=%d ", rec, len );
      dumpEscapedBytes( fp, result, (unsigned long)len );
      fputc( '\n', fp );
   }

   expr4free( fresh );
}

static EXPR4 *parseOne( CODE4 *cb, DATA4 *data, FILE *fp, const EXPRCASE *c )
{
   EXPR4 *expr;

   /* expr4parseLow refuses to start while an error is pending, so a previous
    * refusal would otherwise be reported for every case after it. */
   if ( error4code( cb ) != 0 )
      error4set( cb, 0 );

   expr = expr4parseLow( data, c->text, 0 );
   if ( expr == 0 )
   {
      fprintf( fp, "  PARSE FAILED errorCode=%d\n", (int)error4code( cb ) );
      error4set( cb, 0 );
   }

   return expr;
}

static void dumpCase( FILE *fp, const EXPRCASE *c, int index )
{
   fprintf( fp, "\nexpr %d ", index );
   dumpEscapedBytes( fp, c->text, (unsigned long)strlen( c->text ) );
   if ( c->note != 0 )
      fprintf( fp, "   ; %s", c->note );
   fputc( '\n', fp );
}

/* An expression parsed for a tag is resolved with that tag's context: a bare
 * memo field is capped at the key size (e4parse.c:433-457), and DESCEND/ASCEND
 * of a string is widened by a non-machine collation (:655-672). The dump's own
 * table is used as it is open; another is opened beside it, so that its index
 * -- and a tag of another collation -- can be borrowed, and closed after. */
static int dumpTagCase( FILE *fp, CODE4 *cb, const char *outDir, DATA4 *own,
                        const char *ownName, const TAGCASE *c, int index )
{
   char path[520];
   DATA4 *data = own;
   TAG4 *tag;
   EXPR4 *expr;

   fprintf( fp, "\nexpr %d ", index );
   dumpEscapedBytes( fp, c->text, (unsigned long)strlen( c->text ) );
   if ( c->note != 0 )
      fprintf( fp, "   ; %s", c->note );
   fputc( '\n', fp );

   if ( strcmp( c->table, ownName ) != 0 )
   {
      sprintf( path, "%s\\%s.DBF", outDir, c->table );
      data = d4open( cb, path );
      if ( data == 0 )
         return fail( cb, "d4open for a tag-context parse" );
   }

   tag = d4tag( data, c->tag );
   if ( tag == 0 )
   {
      if ( data != own )
         d4close( data );
      return fail( cb, "d4tag for a tag-context parse" );
   }
   fprintf( fp, "  tag %s.%s collation=%d\n", c->table, c->tag, (int)tag->tagFile->collateName );

   if ( error4code( cb ) != 0 )
      error4set( cb, 0 );

   expr = expr4parseLow( data, c->text, tag->tagFile );
   if ( expr == 0 )
   {
      fprintf( fp, "  PARSE FAILED errorCode=%d\n", (int)error4code( cb ) );
      error4set( cb, 0 );
   }
   else
   {
      dumpNodes( fp, expr );
      expr4free( expr );
   }

   if ( data != own && d4close( data ) < 0 )
      return fail( cb, "d4close after a tag-context parse" );

   return 0;
}

int dumpExpressions( CODE4 *cb, const char *outDir, const char *dbfName,
                     const EXPRCASE *constExprs, int numConst,
                     const EXPRCASE *fieldExprs, int numField,
                     const EXPRCASE *clockExprs, int numClock,
                     const EXPRCASE *rejects,    int numReject,
                     const EXPRCASE *vfpOnly,    int numVfpOnly,
                     const TAGCASE  *tagExprs,   int numTag )
{
   char path[520];
   char stem[260];
   char *dot;
   DATA4 *data;
   FILE *fp;
   long records;
   int i;

   strcpy( stem, dbfName );
   dot = strrchr( stem, '.' );
   if ( dot != 0 )
      *dot = '\0';

   sprintf( path, "%s\\%s.DBF", outDir, stem );
   data = d4open( cb, path );
   if ( data == 0 )
      return fail( cb, "d4open for expression dump" );

   sprintf( path, "%s\\%s.expr.dump.txt", outDir, stem );
   fp = fopen( path, "wb" );
   if ( fp == 0 )
   {
      d4close( data );
      fprintf( stderr, "  ERROR: cannot write %s\n", path );
      return 1;
   }

   records = d4recCount( data );

   dumpHeader( fp, "expression" );
   fprintf( fp, "table        %s.DBF\n", stem );
   fprintf( fp, "numRecs      %ld\n", records );

   /* CTOD and any picture without century digits take the century from the
    * system clock (D4DATE.C:580-601), so a recorded CTOD value is only true
    * inside the century it was generated in. Recording it makes the file
    * self-describing rather than silently stale on 2100-01-01. */
   {
      SYSTEMTIME st ;
      GetLocalTime( &st ) ;
      fprintf( fp, "dateFormat   \"%s\"   (c4code.c:1126, a compile-time constant)\n",
               code4dateFormat( cb ) );
      fprintf( fp, "century      %d   (from the system clock at generation time)\n",
               (int)( st.wYear / 100 ) );
   }

   /* Constant expressions: no field reference, so no record dimension. The
    * table is here only because E4PARM_HIGH insists on one. */
   fprintf( fp, "\n[constant expressions]\ncount        %d\n", numConst );
   if ( numConst > 0 && d4go( data, 1L ) < 0 )
   {
      fclose( fp );
      d4close( data );
      return fail( cb, "d4go 1" );
   }
   for ( i = 0; i < numConst; i++ )
   {
      EXPR4 *expr;

      dumpCase( fp, constExprs + i, i );
      expr = parseOne( cb, data, fp, constExprs + i );
      if ( expr == 0 )
         continue;

      dumpNodes( fp, expr );
      dumpValue( fp, cb, expr, "  value" );
      expr4free( expr );
   }

   /* Field expressions: the types no literal reaches, over every record. */
   fprintf( fp, "\n[field expressions]\ncount        %d\n", numField );
   for ( i = 0; i < numField; i++ )
   {
      EXPR4 *expr;
      KEPTVALUE *sticky;
      long rec;

      dumpCase( fp, fieldExprs + i, i );
      expr = parseOne( cb, data, fp, fieldExprs + i );
      if ( expr == 0 )
         continue;

      dumpNodes( fp, expr );
      sticky = (KEPTVALUE *)calloc( records + 1, sizeof( KEPTVALUE ) );
      for ( rec = 1; rec <= records; rec++ )
      {
         KEPTVALUE *kept = sticky + rec;

         if ( d4go( data, rec ) < 0 )
         {
            fclose( fp );
            d4close( data );
            return fail( cb, "d4go" );
         }
         keepValue( cb, expr, kept );
         if ( kept->bytes == 0 )
            fprintf( fp, "  rec %ld eval-failed rc=%d errorCode=%d\n", rec, kept->len, kept->errorCode );
         else
         {
            fprintf( fp, "  rec %ld len=%d ", rec, kept->len );
            dumpEscapedBytes( fp, kept->bytes, (unsigned long)kept->len );
            fputc( '\n', fp );
         }
      }
      expr4free( expr );

      for ( rec = 1; rec <= records; rec++ )
      {
         if ( d4go( data, rec ) < 0 )
         {
            fclose( fp );
            d4close( data );
            return fail( cb, "d4go" );
         }
         dumpFreshValue( fp, cb, data, fieldExprs[i].text, rec, sticky + rec );
         free( sticky[rec].bytes );
      }
      free( sticky );
   }

   /* Clock-dependent: shape, never a value. DATE() and TIME() read the system
    * clock, so a recorded value would differ on every run -- against the
    * standing requirement that the corpus regenerate byte-identical. Their
    * type, length, key length and node array are all stable, and those are what
    * the port's resolution gate needs. */
   fprintf( fp, "\n[clock-dependent expressions]\ncount        %d\n", numClock );
   for ( i = 0; i < numClock; i++ )
   {
      EXPR4 *expr;

      dumpCase( fp, clockExprs + i, i );
      expr = parseOne( cb, data, fp, clockExprs + i );
      if ( expr == 0 )
         continue;

      dumpNodes( fp, expr );
      fprintf( fp, "  value not-recorded   ; reads the system clock\n" );
      expr4free( expr );
   }

   /* Rejections: what the parser refuses, and with which code. A string that
    * parses is recorded as accepted -- the port must accept exactly these. */
   fprintf( fp, "\n[rejections]\ncount        %d\n", numReject );
   for ( i = 0; i < numReject; i++ )
   {
      EXPR4 *expr;

      if ( error4code( cb ) != 0 )
         error4set( cb, 0 );

      fprintf( fp, "  " );
      dumpEscapedBytes( fp, rejects[i].text, (unsigned long)strlen( rejects[i].text ) );

      expr = expr4parseLow( data, rejects[i].text, 0 );
      if ( expr == 0 )
      {
         fprintf( fp, " rejected errorCode=%d", (int)error4code( cb ) );
         error4set( cb, 0 );
      }
      else
      {
         fprintf( fp, " ACCEPTED type=" );
         dumpTypeCode( fp, expr->type );
         fprintf( fp, " len=%d", expr->len );
         expr4free( expr );
      }

      if ( rejects[i].note != 0 )
         fprintf( fp, "   ; %s", rejects[i].note );
      fputc( '\n', fp );
   }

   /* Names Visual FoxPro has and CodeBase does not. Recorded apart from the
    * rejections on purpose: the port supports them (a CDX written by VFP can
    * carry one in a tag expression, and refusing it would be a read gap, not
    * a safety measure), so this section documents the reference's divergence
    * and must never be read as "the port refuses these". */
   fprintf( fp, "\n[vfp-only]\ncount        %d\n", numVfpOnly );
   fprintf( fp, "# CodeBase refuses every one of these. This port does not --\n" );
   fprintf( fp, "# see claude/dev/010-expr/DESIGN.md Decision 11.\n" );
   for ( i = 0; i < numVfpOnly; i++ )
   {
      EXPR4 *expr;

      if ( error4code( cb ) != 0 )
         error4set( cb, 0 );

      fprintf( fp, "  " );
      dumpEscapedBytes( fp, vfpOnly[i].text, (unsigned long)strlen( vfpOnly[i].text ) );

      expr = expr4parseLow( data, vfpOnly[i].text, 0 );
      if ( expr == 0 )
      {
         fprintf( fp, " codebase-refuses errorCode=%d", (int)error4code( cb ) );
         error4set( cb, 0 );
      }
      else
      {
         fprintf( fp, " CODEBASE-ACCEPTS type=" );
         dumpTypeCode( fp, expr->type );
         expr4free( expr );
      }

      if ( vfpOnly[i].note != 0 )
         fprintf( fp, "   ; %s", vfpOnly[i].note );
      fputc( '\n', fp );
   }

   /* Shape only, as the clock section: what changes is lengths, and a value
    * would be the same as the unlinked parse's. */
   fprintf( fp, "\n[tag context]\ncount        %d\n", numTag );
   for ( i = 0; i < numTag; i++ )
   {
      if ( dumpTagCase( fp, cb, outDir, data, stem, tagExprs + i, i ) != 0 )
      {
         fclose( fp );
         d4close( data );
         return 1;
      }
   }

   fclose( fp );

   if ( d4close( data ) < 0 )
      return fail( cb, "d4close after expression dump" );

   return 0;
}
