<#
  run-in-vm.ps1 -- runs a VFP oracle script in the VFP 9 VM, unattended,
  through VMware Workstation's vmrun (ADR-44; step 013, sub-step 7a-6).

      run-in-vm.ps1                              vfpfunc.prg, 600 s
      run-in-vm.ps1 -Script other.prg -TimeoutSeconds 120

  The VM must already be running with its user logged in: VFP is a GUI
  program and vmrun -interactive runs it in that user's session. This script
  never starts or stops the VM.

  The script is copied into the guest with a generated wrapper that runs it
  with the guest's output folder, writes OK or the error into done.txt and the
  console into console.txt, and quits -- so an error VFP does not trap cannot
  open a dialog nobody sees. A run past -TimeoutSeconds has its vfp9.exe
  killed in the guest and fails.

  Output lands in .\out\ beside this file, emptied first, which is where
  copy-vfp-corpus.bat publishes from. Nothing is published by this script.

  Configuration, all from the environment, none of it in the repository:
      VFP_VM_VMX    the VM's .vmx file                          (required)
      VFP_VM_USER   the guest's logged-in user                  (required)
      VFP_VM_PASS   that user's password                        (required)
      VFP_VM_EXE    vfp9.exe in the guest   (default below)
      VMRUN         vmrun.exe on the host   (default below)
#>
param(
    [string] $Script = "vfpfunc.prg",
    [int] $TimeoutSeconds = 600
)

$GuestJob = "C:\vfpjob"
$GuestOut = "$GuestJob\out"

function Fail([string] $message) {
    Write-Host "[run-in-vm] ERROR: $message"
    exit 1
}

function Setting([string] $name, [string] $default) {
    $value = [Environment]::GetEnvironmentVariable($name)
    if ([string]::IsNullOrEmpty($value)) { $value = $default }
    if ([string]::IsNullOrEmpty($value)) { Fail "$name is not set" }
    return $value
}

# One argument as CreateProcess parses it: quoted, with embedded quotes and the
# backslashes before them escaped.
function Quote([string] $text) {
    $escaped = $text -replace '(\\*)"', '$1$1\"'
    $escaped = $escaped -replace '(\\+)$', '$1$1'
    return '"' + $escaped + '"'
}

$vmx  = Setting "VFP_VM_VMX" ""
$user = Setting "VFP_VM_USER" ""
$pass = Setting "VFP_VM_PASS" ""
$exe  = Setting "VFP_VM_EXE" "C:\Program Files\Microsoft Visual FoxPro 9\vfp9.exe"
$vmrun = Setting "VMRUN" "C:\Program Files\VMware\VMware Workstation\vmrun.exe"

if (-not (Test-Path -LiteralPath $vmrun)) { Fail "vmrun not found: $vmrun" }

$here = $PSScriptRoot
$source = if ([IO.Path]::IsPathRooted($Script)) { $Script } else { Join-Path $here $Script }
if (-not (Test-Path -LiteralPath $source)) { Fail "no such script: $source" }
$Script = [IO.Path]::GetFileName($source)
$hostOut = Join-Path $here "out"

# A guest operation; fails the run on a non-zero exit, with vmrun's own message.
function Guest([string[]] $arguments) {
    $output = & $vmrun -T ws -gu $user -gp $pass @arguments
    if ($LASTEXITCODE -ne 0) { Fail "vmrun $($arguments[0]): $output" }
    return $output
}

function KillVfpInGuest {
    $exeName = [IO.Path]::GetFileName($exe)
    foreach ($line in (& $vmrun -T ws -gu $user -gp $pass listProcessesInGuest $vmx)) {
        if ($line -match '^pid=(\d+),.*cmd=.*' + [regex]::Escape($exeName)) {
            & $vmrun -T ws -gu $user -gp $pass killProcessInGuest $vmx $Matches[1] | Out-Null
            Write-Host "[run-in-vm] killed $exeName (pid $($Matches[1])) in the guest"
        }
    }
}

# 1. The VM is running; this script does not start it.
$running = & $vmrun -T ws list
if ($LASTEXITCODE -ne 0) { Fail "vmrun list: $running" }
if (-not ($running | Where-Object { $_.Trim() -ieq $vmx })) { Fail "the VM is not running: $vmx" }

# 2. A clean host out\, so nothing from an earlier run can be published as this one's.
if (Test-Path -LiteralPath $hostOut) { Remove-Item -LiteralPath $hostOut -Recurse -Force }
New-Item -ItemType Directory -Path $hostOut | Out-Null

# 3. A clean guest job folder, the script and its wrapper.
if (-not ((Guest @("directoryExistsInGuest", $vmx, $GuestJob)) -match "does not exist")) {
    Guest @("deleteDirectoryInGuest", $vmx, $GuestJob) | Out-Null
}
Guest @("createDirectoryInGuest", $vmx, $GuestJob) | Out-Null
Guest @("CopyFileFromHostToGuest", $vmx, $source, "$GuestJob\$Script") | Out-Null

$wrapper = @(
    "* runjob.prg -- generated by run-in-vm.ps1; not part of the repository",
    "LOCAL lcErr, loEx",
    "lcErr = """"",
    "SET SAFETY OFF",
    "SET ALTERNATE TO ""$GuestJob\console.txt""",
    "SET ALTERNATE ON",
    "TRY",
    "   DO ""$GuestJob\$Script"" WITH ""$GuestOut""",
    "CATCH TO loEx",
    "   lcErr = TRANSFORM(loEx.ErrorNo) + "" "" + loEx.Message + "" | "" + loEx.Procedure + "" line "" + TRANSFORM(loEx.LineNo)",
    "ENDTRY",
    "SET ALTERNATE OFF",
    "SET ALTERNATE TO",
    "= STRTOFILE(IIF(EMPTY(m.lcErr), ""OK"", m.lcErr), ""$GuestJob\done.txt"")",
    "QUIT"
)
$local = Join-Path $hostOut "runjob.prg"
[IO.File]::WriteAllText($local, ($wrapper -join "`r`n") + "`r`n", [Text.Encoding]::ASCII)
Guest @("CopyFileFromHostToGuest", $vmx, $local, "$GuestJob\runjob.prg") | Out-Null
Remove-Item -LiteralPath $local

# 4. Run, bounded by the timeout. vmrun blocks while the program runs, so the
#    bound is on the vmrun process.
Write-Host "[run-in-vm] $Script in the guest (timeout $TimeoutSeconds s)"
$arguments = @("-T", "ws", "-gu", $user, "-gp", $pass, "runProgramInGuest", $vmx,
               "-interactive", $exe, "-t", "$GuestJob\runjob.prg") | ForEach-Object { Quote $_ }
$process = Start-Process -FilePath $vmrun -ArgumentList $arguments -NoNewWindow -PassThru
$null = $process.Handle   # keeps ExitCode readable after the process ends (Windows PowerShell)
if (-not $process.WaitForExit($TimeoutSeconds * 1000)) {
    KillVfpInGuest
    if (-not $process.HasExited) { $process.Kill() }
    Fail "timed out after $TimeoutSeconds s"
}
if ($process.ExitCode -ne 0) { Fail "vmrun runProgramInGuest exited $($process.ExitCode)" }

# 5. The verdict, the console, and -- only on success -- the output.
$done = Join-Path $hostOut "done.txt"
& $vmrun -T ws -gu $user -gp $pass CopyFileFromGuestToHost $vmx "$GuestJob\done.txt" $done | Out-Null
if ($LASTEXITCODE -ne 0) { Fail "the run left no done.txt: VFP did not reach the end of the wrapper" }
Guest @("CopyFileFromGuestToHost", $vmx, "$GuestJob\console.txt", (Join-Path $hostOut "console.txt")) | Out-Null
Get-Content -LiteralPath (Join-Path $hostOut "console.txt") | ForEach-Object { Write-Host "[vfp] $_" }

$verdict = (Get-Content -LiteralPath $done -Raw).Trim()
Remove-Item -LiteralPath $done
if ($verdict -ne "OK") { Fail "the script failed: $verdict" }

$listing = Guest @("listDirectoryInGuest", $vmx, $GuestOut)
foreach ($name in ($listing | Select-Object -Skip 1)) {
    if ([string]::IsNullOrWhiteSpace($name)) { continue }
    Guest @("CopyFileFromGuestToHost", $vmx, "$GuestOut\$name", (Join-Path $hostOut $name)) | Out-Null
    Write-Host "[run-in-vm]      $name"
}

Write-Host "[run-in-vm] OK -> $hostOut"
exit 0
